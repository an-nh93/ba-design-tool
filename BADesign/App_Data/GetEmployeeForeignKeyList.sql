-- Danh sach bang script se XOA (de Step 2b chi kiem tra FK tham chieu cac bang nay -> nhanh hon)
-- Dung recursive CTE 1 lan thay vi 5 UNION (nhanh hon)
DECLARE @TablesInsert NVARCHAR(MAX) = N'';
;WITH R AS (
    SELECT parent_object_id AS obj_id, 1 AS lvl
    FROM sys.foreign_keys
    WHERE referenced_object_id = @EmployeeTableID
    UNION ALL
    SELECT fk.parent_object_id, R.lvl + 1
    FROM R
    INNER JOIN sys.foreign_keys fk ON fk.referenced_object_id = R.obj_id
    WHERE R.lvl < 4
),
TablesWeDelete AS (
    SELECT DISTINCT OBJECT_SCHEMA_NAME(obj_id) AS Sn, OBJECT_NAME(obj_id) AS Tn FROM R
    UNION
    SELECT OBJECT_SCHEMA_NAME(@EmployeeTableID), OBJECT_NAME(@EmployeeTableID)
    UNION
    SELECT OBJECT_SCHEMA_NAME(parent_object_id), OBJECT_NAME(parent_object_id)
    FROM sys.foreign_keys
    WHERE (name LIKE N'FK_Security_GroupUsers_Security_Users%' OR (OBJECT_NAME(parent_object_id) = N'Security_GroupUsers' AND OBJECT_NAME(referenced_object_id) = N'Security_Users'))
)
SELECT @TablesInsert = (SELECT N'(N''' + REPLACE(REPLACE(Sn, N'''', N''''''), N'\', N'\\') + N''',N''' + REPLACE(REPLACE(Tn, N'''', N''''''), N'\', N'\\') + N'''),' FROM TablesWeDelete FOR XML PATH(''), TYPE).value(N'.', N'NVARCHAR(MAX)');
SET @TablesInsert = CASE WHEN LEN(ISNULL(@TablesInsert,N'')) = 0 THEN N'(N''dbo'',N''' + REPLACE(@EmployeeTable, N'''', N'''''') + N''')' ELSE LEFT(@TablesInsert, LEN(@TablesInsert)-1) END;

