FROM sys.foreign_keys AS fk1
INNER JOIN sys.foreign_key_columns AS fkc1 ON fk1.object_id = fkc1.constraint_object_id AND fk1.referenced_object_id = @EmployeeTableID
INNER JOIN sys.foreign_keys AS fk2 ON fk2.referenced_object_id = fk1.parent_object_id
INNER JOIN sys.foreign_key_columns AS fkc2 ON fk2.object_id = fkc2.constraint_object_id
