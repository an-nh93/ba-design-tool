-- App doc result set 2: noi tat ca Chunk theo ChunkSeq de duoc script day du
DECLARE @FullScript NVARCHAR(MAX) = (SELECT Line + @CRLF FROM (SELECT Seq, Line FROM @Lines) L ORDER BY Seq FOR XML PATH(N''), TYPE).value(N'.', N'NVARCHAR(MAX)');
DECLARE @ChunkSize INT = 8000, @Off INT = 1, @LastCrlf INT, @Chunk NVARCHAR(MAX), @ChunkSeq INT = 0;
CREATE TABLE #Chunks (ChunkSeq INT, Chunk NVARCHAR(MAX));
WHILE @Off <= LEN(@FullScript)
BEGIN
    SET @ChunkSeq = @ChunkSeq + 1;
    IF @Off + @ChunkSize >= LEN(@FullScript)
        SET @Chunk = SUBSTRING(@FullScript, @Off, LEN(@FullScript) - @Off + 1);
    ELSE
    BEGIN
        SET @LastCrlf = 0;
        SELECT @LastCrlf = MAX(n) FROM (SELECT number AS n FROM master..spt_values WHERE type = N'P' AND number BETWEEN 1 AND @ChunkSize) N
        WHERE SUBSTRING(@FullScript, @Off + n - 1, 2) = @CRLF;
        IF @LastCrlf > 0
            SET @Chunk = SUBSTRING(@FullScript, @Off, @LastCrlf + 2);
        ELSE
            SET @Chunk = SUBSTRING(@FullScript, @Off, @ChunkSize);
    END
    INSERT INTO #Chunks (ChunkSeq, Chunk) VALUES (@ChunkSeq, @Chunk);
    SET @Off = @Off + LEN(@Chunk);
END;
SELECT ChunkSeq, Chunk FROM #Chunks ORDER BY ChunkSeq;
DROP TABLE #Chunks;

