SELECT
    N'        DELETE FROM '
    + QUOTENAME(OBJECT_SCHEMA_NAME(fk3.parent_object_id)) + N'.' + QUOTENAME(OBJECT_NAME(fk3.parent_object_id))
    + N' WHERE '
    + QUOTENAME(CAST(COL_NAME(fkc3.parent_object_id, fkc3.parent_column_id) AS NVARCHAR(128)))
    + N' IN (SELECT '
    + QUOTENAME(CAST(COL_NAME(fkc3.referenced_object_id, fkc3.referenced_column_id) AS NVARCHAR(128)))
    + N' FROM '
    + QUOTENAME(OBJECT_SCHEMA_NAME(fk3.referenced_object_id)) + N'.' + QUOTENAME(OBJECT_NAME(fk3.referenced_object_id))
    + N' WHERE '
    + QUOTENAME(CAST(COL_NAME(fkc2.parent_object_id, fkc2.parent_column_id) AS NVARCHAR(128)))
    + N' IN (SELECT '
    + QUOTENAME(CAST(COL_NAME(fkc2.referenced_object_id, fkc2.referenced_column_id) AS NVARCHAR(128)))
    + N' FROM '
    + QUOTENAME(OBJECT_SCHEMA_NAME(fk2.referenced_object_id)) + N'.' + QUOTENAME(OBJECT_NAME(fk2.referenced_object_id))
