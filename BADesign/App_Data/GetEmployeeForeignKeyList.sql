-- Tach header vao bang dong (tranh noi chuoi khong lo trong cursor -> nhanh hon)
DECLARE @Lines TABLE (Seq INT, Line NVARCHAR(MAX));
DECLARE @Pos INT = 1, @Next INT, @Len INT, @Seq INT = 0;
SET @Len = LEN(@Script);
WHILE @Pos <= @Len
BEGIN
    SET @Next = CHARINDEX(@CRLF, @Script + @CRLF, @Pos);
    SET @Seq = @Seq + 1;
    INSERT INTO @Lines (Seq, Line) VALUES (@Seq, SUBSTRING(@Script, @Pos, @Next - @Pos));
    SET @Pos = @Next + 2;
END;
SET @Seq = (SELECT MAX(Seq) FROM @Lines);

