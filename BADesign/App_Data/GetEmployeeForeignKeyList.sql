-- Danh sach bang script se XOA (de Step 2b chi kiem tra FK tham chieu cac bang nay -> nhanh hon)
DECLARE @TablesInsert NVARCHAR(MAX) = N'';
;WITH TablesWeDelete AS (
    SELECT DISTINCT OBJECT_SCHEMA_NAME(fk3.parent_object_id) AS Sn, OBJECT_NAME(fk3.parent_object_id) AS Tn
    FROM sys.foreign_keys AS fk1
    INNER JOIN sys.foreign_key_columns AS fkc1 ON fk1.object_id = fkc1.constraint_object_id AND fk1.referenced_object_id = @EmployeeTableID
    INNER JOIN sys.foreign_keys AS fk2 ON fk2.referenced_object_id = fk1.parent_object_id
    INNER JOIN sys.foreign_key_columns AS fkc2 ON fk2.object_id = fkc2.constraint_object_id
    INNER JOIN sys.foreign_keys AS fk3 ON fk3.referenced_object_id = fk2.parent_object_id
    INNER JOIN sys.foreign_key_columns AS fkc3 ON fk3.object_id = fkc3.constraint_object_id
    WHERE fk3.parent_object_id <> @EmployeeTableID
    UNION
    SELECT DISTINCT OBJECT_SCHEMA_NAME(fk2.parent_object_id), OBJECT_NAME(fk2.parent_object_id)
    FROM sys.foreign_keys AS fk1
    INNER JOIN sys.foreign_key_columns AS fkc1 ON fk1.object_id = fkc1.constraint_object_id AND fk1.referenced_object_id = @EmployeeTableID
    INNER JOIN sys.foreign_keys AS fk2 ON fk2.referenced_object_id = fk1.parent_object_id
    INNER JOIN sys.foreign_key_columns AS fkc2 ON fk2.object_id = fkc2.constraint_object_id
    WHERE fk2.parent_object_id <> @EmployeeTableID
    UNION
    SELECT DISTINCT OBJECT_SCHEMA_NAME(fk.parent_object_id), OBJECT_NAME(fk.parent_object_id)
    FROM sys.foreign_keys AS fk
    INNER JOIN sys.foreign_key_columns AS fkc ON fk.object_id = fkc.constraint_object_id
    WHERE fk.referenced_object_id = @EmployeeTableID
    UNION
    SELECT DISTINCT OBJECT_SCHEMA_NAME(fk.parent_object_id), OBJECT_NAME(fk.parent_object_id)
    FROM sys.foreign_keys fk
    INNER JOIN sys.foreign_key_columns fkc ON fk.object_id = fkc.constraint_object_id
    WHERE (fk.name LIKE N'FK_Security_GroupUsers_Security_Users%' OR (OBJECT_NAME(fk.parent_object_id) = N'Security_GroupUsers' AND OBJECT_NAME(fk.referenced_object_id) = N'Security_Users'))
    UNION
    SELECT OBJECT_SCHEMA_NAME(@EmployeeTableID), OBJECT_NAME(@EmployeeTableID)
)
SELECT @TablesInsert = (SELECT N'(N''' + REPLACE(REPLACE(Sn, N'''', N''''''), N'\', N'\\') + N''',N''' + REPLACE(REPLACE(Tn, N'''', N''''''), N'\', N'\\') + N'''),' FROM TablesWeDelete FOR XML PATH(''), TYPE).value(N'.', N'NVARCHAR(MAX)');
SET @TablesInsert = CASE WHEN LEN(ISNULL(@TablesInsert,N'')) = 0 THEN N'(N''dbo'',N''' + REPLACE(@EmployeeTable, N'''', N'''''') + N''')' ELSE LEFT(@TablesInsert, LEN(@TablesInsert)-1) END;

